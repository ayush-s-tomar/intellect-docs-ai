-- AskMyDocs: database schema
-- Run top to bottom on a fresh Supabase project to recreate everything.
-- Idempotent: safe to re-run on an existing database.

-- 1. pgvector for similarity search
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Core tables
CREATE TABLE IF NOT EXISTS documents (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chunks (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id bigint NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  content     text NOT NULL,
  chunk_index integer
);

-- Position of the chunk within its document (written by /api/upload).
ALTER TABLE chunks ADD COLUMN IF NOT EXISTS chunk_index integer;

-- 3. Document metadata
ALTER TABLE documents ADD COLUMN IF NOT EXISTS summary TEXT;

-- 4. Session-scoped multi-user isolation (see useSessionId.ts)
ALTER TABLE documents ADD COLUMN IF NOT EXISTS session_id TEXT;
ALTER TABLE chunks ADD COLUMN IF NOT EXISTS session_id TEXT;

CREATE INDEX IF NOT EXISTS idx_documents_session_id ON documents(session_id);
CREATE INDEX IF NOT EXISTS idx_chunks_session_id ON chunks(session_id);

-- 4b. Row Level Security. All access goes through API routes using the
-- service-role key, which bypasses RLS. Enabling RLS with no policies means
-- the public anon key can read and write nothing, even if it ever leaks.
ALTER TABLE documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE chunks ENABLE ROW LEVEL SECURITY;

-- 5. Embedding storage: 384 dimensions (Cohere embed-english-light-v3.0).
-- No ANN index on purpose: every query is filtered to one session and the
-- selected documents first, so the candidate set is small and an exact scan
-- is fast and gives exact recall.
ALTER TABLE chunks ADD COLUMN IF NOT EXISTS embedding_v2 vector(384);

-- 6. Vector-only search (cosine similarity). Not used by /api/chat, which
-- calls hybrid_search_chunks; kept as a vector-only baseline (see
-- searchChunksVectorOnly in chunks-repository.ts).
--
-- Zero vectors are excluded using L2 distance against the zero vector,
-- which is dimension-agnostic.
CREATE OR REPLACE FUNCTION match_chunks(
  query_embedding vector(384),
  match_count int,
  filter_session_id text,
  filter_doc_ids bigint[]
)
RETURNS TABLE (
  content text,
  document_id bigint,
  similarity float
)
LANGUAGE sql STABLE
AS $$
  SELECT
    content,
    document_id,
    1 - (embedding_v2 <=> query_embedding) AS similarity
  FROM chunks
  WHERE
    session_id = filter_session_id
    AND document_id = ANY(filter_doc_ids)
    AND embedding_v2 IS NOT NULL
    AND embedding_v2 <-> array_fill(0, ARRAY[384])::vector != 0
  ORDER BY embedding_v2 <=> query_embedding
  LIMIT match_count;
$$;

-- ============================================================
-- 7. Hybrid search: vector + full-text, fused with RRF
-- ============================================================
--
-- Pure vector search can miss exact keywords, names and numbers (for
-- example "Q3 2024" or a proper noun can rank poorly on cosine similarity
-- even when the literal term is in a chunk). This adds Postgres full-text
-- search alongside vector search and fuses the two ranked lists with
-- Reciprocal Rank Fusion, a tuning-free way to combine different rankers:
--
--   RRF_score(chunk) = SUM over rankers i of 1 / (k + rank_i(chunk)),  k = 60
--
-- k = 60 is the constant from the original RRF paper: large enough that no
-- single top rank dominates, small enough that rank position still matters.

-- 7a. Full-text column + index. GENERATED ALWAYS ... STORED keeps it in
-- sync with `content` automatically: no trigger, no drift.
ALTER TABLE chunks
  ADD COLUMN IF NOT EXISTS content_tsv tsvector
  GENERATED ALWAYS AS (to_tsvector('english', content)) STORED;

CREATE INDEX IF NOT EXISTS idx_chunks_content_tsv
  ON chunks USING GIN (content_tsv);

-- 7b. Hybrid search RPC used by /api/chat and /api/eval.
--
-- websearch_to_tsquery ANDs every term, so a natural-language question
-- ("what is the candidate's experience with Python?") would only match a
-- chunk containing ALL of its words. The query is rewritten to OR the terms
-- instead, and ts_rank orders chunks by how many terms they match.
--
-- `similarity` is real cosine similarity for every returned chunk, including
-- chunks found only by the full-text leg. `rrf_score` is the fused rank score
-- used for ordering.
CREATE OR REPLACE FUNCTION hybrid_search_chunks(
  query_text text,
  query_embedding vector(384),
  match_count int,
  filter_session_id text,
  filter_doc_ids bigint[],
  rrf_k int DEFAULT 60
)
RETURNS TABLE (
  content text,
  document_id bigint,
  similarity float,
  rrf_score float
)
LANGUAGE sql STABLE
AS $$
  WITH q AS (
    SELECT
      CASE
        WHEN numnode(w.tsq) = 0 THEN w.tsq
        ELSE replace(w.tsq::text, ' & ', ' | ')::tsquery
      END AS tsq
    FROM (SELECT websearch_to_tsquery('english', query_text) AS tsq) w
  ),
  vector_ranked AS (
    SELECT
      c.id,
      c.content,
      c.document_id,
      1 - (c.embedding_v2 <=> query_embedding) AS similarity,
      ROW_NUMBER() OVER (ORDER BY c.embedding_v2 <=> query_embedding) AS rnk
    FROM chunks c
    WHERE
      c.session_id = filter_session_id
      AND c.document_id = ANY(filter_doc_ids)
      AND c.embedding_v2 IS NOT NULL
      AND c.embedding_v2 <-> array_fill(0, ARRAY[384])::vector != 0
    ORDER BY c.embedding_v2 <=> query_embedding
    LIMIT LEAST(match_count * 4, 40)
  ),
  text_ranked AS (
    SELECT
      c.id,
      c.content,
      c.document_id,
      1 - (c.embedding_v2 <=> query_embedding) AS similarity,
      ts_rank(c.content_tsv, q.tsq) AS text_score,
      ROW_NUMBER() OVER (ORDER BY ts_rank(c.content_tsv, q.tsq) DESC, c.id) AS rnk
    FROM chunks c, q
    WHERE
      c.session_id = filter_session_id
      AND c.document_id = ANY(filter_doc_ids)
      AND c.content_tsv @@ q.tsq
    ORDER BY text_score DESC, c.id
    LIMIT LEAST(match_count * 4, 40)
  ),
  fused AS (
    SELECT
      COALESCE(v.id, t.id) AS id,
      COALESCE(v.content, t.content) AS content,
      COALESCE(v.document_id, t.document_id) AS document_id,
      COALESCE(v.similarity, t.similarity) AS similarity,
      (COALESCE(1.0 / (rrf_k + v.rnk), 0) + COALESCE(1.0 / (rrf_k + t.rnk), 0))::float AS rrf_score
    FROM vector_ranked v
    FULL OUTER JOIN text_ranked t ON v.id = t.id
  )
  SELECT content, document_id, similarity, rrf_score
  FROM fused
  ORDER BY rrf_score DESC
  LIMIT match_count;
$$;

-- ============================================================
-- 8. Security hardening: pin search_path on both functions
-- ============================================================
-- Supabase's linter flags functions with a mutable search_path. Pinning it
-- stops a caller from shadowing objects via their own schema. This section
-- must stay LAST: CREATE OR REPLACE FUNCTION above resets function settings.
ALTER FUNCTION public.match_chunks(vector, int, text, bigint[])
  SET search_path = public;

ALTER FUNCTION public.hybrid_search_chunks(text, vector, int, text, bigint[], int)
  SET search_path = public;